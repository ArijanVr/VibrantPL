import AppKit
import VibrantPlusKit

final class LinkCleanerService {
    static let shared = LinkCleanerService()
    private var timer: Timer?
    private var lastChange = NSPasteboard.general.changeCount
    func update() {
        guard Prefs.shared.isOn(.links) && Prefs.shared.autoCleanLinks else { stop(); return }
        guard timer == nil else { return }
        lastChange = NSPasteboard.general.changeCount
        timer = Timer.repeating(every: 1) { _ in MainActor.assumeIsolated { LinkCleanerService.shared.poll() } }
    }
    func stop() { timer?.invalidate(); timer = nil }
    private func poll() {
        let pb = NSPasteboard.general
        guard pb.changeCount != lastChange else { return }
        lastChange = pb.changeCount
        let privateTypes: Set<String> = ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType"]
        guard !(pb.types ?? []).contains(where: { privateTypes.contains($0.rawValue) }),
              let original = pb.string(forType: .string), let cleaned = CleanLink.clean(original), cleaned != original else { return }
        pb.clearContents()
        pb.setString(cleaned, forType: .string)
        pb.setString(cleaned, forType: .URL)
        lastChange = pb.changeCount
    }
}
